const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844},acceptDownloads:true});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>{window.badgeText=[];const original=CanvasRenderingContext2D.prototype.fillText;CanvasRenderingContext2D.prototype.fillText=function(t,...args){window.badgeText.push(t);return original.call(this,t,...args);};});
  const base=process.env.TEST_URL||'http://127.0.0.1:8000/bird-explorer/';
  await page.goto(base+'?area=limestone-canyon');
  assert.match(await page.locator('#welcome-title').textContent(),/Limestone Canyon/);
  await page.screenshot({path:'/tmp/trail-welcome-mobile.png',fullPage:true});
  await page.locator('summary').click();
  await page.locator('#welcome-area').selectOption('weir-canyon');
  assert.match(await page.locator('#welcome-title').textContent(),/Weir Canyon/);
  assert.equal(await page.locator('#discovery-area').inputValue(),'weir-canyon');
  await page.locator('#welcome-area').selectOption('other');
  await page.locator('#welcome-other').fill('Local park');
  assert.match(await page.locator('#welcome-title').textContent(),/Local park/);
  await page.locator('#get-started').click();
  await page.getByRole('heading',{name:'Start with a quiet pause.'}).waitFor();
  await page.locator('#ready-observe').click();
  await page.waitForFunction(()=>document.querySelectorAll('.species-card').length===5);
  await page.getByRole('button',{name:'On the ground',exact:true}).click();
  assert.equal(await page.locator('.species-card').count(),3);
  await page.getByRole('button',{name:'Flying or hovering',exact:true}).click();
  assert.equal(await page.locator('.species-card').count(),2);
  await page.getByRole('button',{name:'I heard it',exact:true}).click();
  await page.locator('#search').fill('wrentit');
  await page.locator('.species-card').click();
  assert.match(await page.locator('.field-tips').textContent(),/Look for.*Notice.*habitat/s);
  await page.getByRole('button',{name:'Compare other birds'}).click();
  await page.getByRole('button',{name:'Get help with Merlin'}).click();
  await page.locator('#merlin-close').click();
  await page.locator('.species-card').click();
  await page.getByRole('button',{name:'Create My Badge'}).click();
  const ready=()=>page.waitForFunction(()=>!document.querySelector('#download').disabled);
  await ready();assert.equal(await page.locator('#encounter').inputValue(),'heard');
  await page.locator('#field-note').fill('Calling from a shrub beside the trail.');await ready();
  await page.locator('#encounter').selectOption('both');await ready();
  const text=await page.evaluate(()=>window.badgeText);
  assert(text.includes('Observed: Seen and heard'));assert(text.includes('Calling from a shrub beside the trail.'));
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#download').click()]);
  const bytes=await fs.readFile(await download.path());
  assert.deepEqual(bytes,Buffer.from(await page.locator('#badge-canvas').evaluate(c=>c.toDataURL().split(',')[1]),'base64'));
  assert.match(await page.locator('#learn-bird').getAttribute('href'),/\/Wrentit\/overview$/);
  assert((await page.locator('#stewardship-text').textContent()).length>20);
  await page.screenshot({path:'/tmp/trail-field-note-mobile.png',fullPage:true});
  await page.setViewportSize({width:320,height:740});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.locator('#notice-another').click();
  assert.equal(await page.locator('.species-card').count(),5);
  assert.equal(await page.locator('#field-note').inputValue(),'');
  assert.equal(await page.locator('#other-location').inputValue(),'Local park');
  await page.goto(base+'?area=unknown');
  assert.equal(await page.locator('#welcome-title').textContent(),'Explore birds around you.');
  await page.route('**/assets/areas/*.webp',r=>r.abort());await page.reload();
  await page.locator('#find-bird').click();await page.locator('.species-card').first().click();
  await page.getByRole('button',{name:'Create My Badge'}).click();await ready();
  assert.deepEqual(errors,[]);
  console.log('Trail flow passed: location changes/custom/fallback, guided pause, clue browsing, tips/comparison/Merlin, seen/heard field notes in matching PNG, stewardship, repeat observation, mobile and failed artwork.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
